<?php
session_start();
if (!isset($_SESSION['username'])) {
    header("Location: index.php");
    exit;
}

include "config/database.php";

$action = $_POST['action'] ?? '';
$msg = 'stock_added';

if ($action === 'add_new') {

    $name     = trim($_POST['name'] ?? '');
    $category = trim($_POST['category'] ?? '');
    $batch    = trim($_POST['batch_no'] ?? '');
    $expiry   = $_POST['expiry_date'] ?? '';
    $qty      = intval($_POST['quantity'] ?? 0);
    $price    = floatval($_POST['price'] ?? 0);

    if ($name !== '' && $batch !== '' && $expiry !== '' && $qty >= 0 && $price >= 0) {

        // Med_ID isn't auto-generated by the database, so work out the next one here
        // (same approach as Cust_ID / Supp_ID). Keeps whatever prefix existing IDs use (e.g. M001).
        $prefix = 'M';
        $number = 1;
        $result = $conn->query("SELECT Med_ID FROM medicines ORDER BY LENGTH(Med_ID) DESC, Med_ID DESC LIMIT 1");
        if ($result && $row = $result->fetch_assoc()) {
            if (preg_match('/^(\D*)(\d+)$/', (string)$row['Med_ID'], $m)) {
                $prefix = $m[1];
                $number = intval($m[2]) + 1;
            }
        }
        $newId = $prefix . str_pad($number, 3, '0', STR_PAD_LEFT);

        // No restriction on the expiry date: past, present and future dates are all accepted.
        $categoryOrNull = $category === '' ? null : $category;

        try {
            $stmt = $conn->prepare("
                INSERT INTO medicines (Med_ID, Name, Category, Batch_No, Expiry_Date, Quantity, Price)
                VALUES (?, ?, ?, ?, ?, ?, ?)
            ");
            $stmt->bind_param("sssssid", $newId, $name, $categoryOrNull, $batch, $expiry, $qty, $price);
            $stmt->execute();
            $msg = 'medicine_added';
        } catch (mysqli_sql_exception $e) {
            $_SESSION['stock_error'] = $e->getMessage();
            $msg = 'medicine_error';
        }
    } else {
        $msg = 'medicine_error';
        $_SESSION['stock_error'] = 'Please fill in all fields correctly.';
    }

} elseif ($action === 'restock') {

    $medicineID = $_POST['medicine_id'] ?? '';
    $addQty     = intval($_POST['add_quantity'] ?? 0);

    if ($medicineID !== '' && $addQty > 0) {
        $stmt = $conn->prepare("UPDATE medicines SET Quantity = Quantity + ? WHERE Med_ID = ?");
        $stmt->bind_param("is", $addQty, $medicineID);
        $stmt->execute();
    }
}

$conn->close();
header("Location: dashboard.php?tab=stock&msg=" . urlencode($msg));
exit;
?>
