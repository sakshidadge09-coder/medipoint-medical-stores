<?php
session_start();
header('Content-Type: application/json');

if (!isset($_SESSION['username'])) {
    http_response_code(401);
    echo json_encode(['success' => false, 'message' => 'Session expired. Please log in again.']);
    exit;
}

include "config/database.php";

$name    = trim($_POST['name'] ?? '');
$contact = trim($_POST['contact'] ?? '');
$address = trim($_POST['address'] ?? '');

if ($name === '' || $contact === '' || $address === '') {
    echo json_encode(['success' => false, 'message' => 'Name, contact, and address are required.']);
    exit;
}

// Supp_ID isn't auto-generated by the database, so work out the next one here (S001, S002, ...)
$newId = 'S001';
$result = $conn->query("SELECT Supp_ID FROM suppliers ORDER BY Supp_ID DESC LIMIT 1");
if ($result && $row = $result->fetch_assoc()) {
    $number = intval(substr($row['Supp_ID'], 1)) + 1;
    $newId = 'S' . str_pad($number, 3, '0', STR_PAD_LEFT);
}

$stmt = $conn->prepare("INSERT INTO suppliers (Supp_ID, Name, Contact, Address) VALUES (?, ?, ?, ?)");
$stmt->bind_param("ssss", $newId, $name, $contact, $address);

if ($stmt->execute()) {
    echo json_encode([
        'success' => true,
        'supp_id' => $newId,
        'name'    => $name,
        'contact' => $contact,
        'address' => $address
    ]);
} else {
    echo json_encode(['success' => false, 'message' => 'Could not add supplier: ' . $stmt->error]);
}

$conn->close();
?>